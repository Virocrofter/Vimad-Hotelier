import { chromium } from 'playwright';
const WEB = 'http://localhost:5173';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('PAGE_ERROR:', String(e).slice(0, 180)));
page.on('console', (m) => {
  if (m.type() === 'error') console.log('CONSOLE_ERROR:', m.text().slice(0, 180));
});
await page.goto(WEB + '/auth/login');
await page.locator('#tenantSlug').fill('demo-hotel');
await page.locator('#email').fill('admin@demo.com');
await page.locator('#password').fill('admin123');
await page.locator('button[type="submit"]').click();
await page.waitForURL('**/app/**', { timeout: 20000 });
await page.goto(WEB + '/app/exceptions');
await page.waitForTimeout(3000);
await page.locator('section[aria-label="Needs attention"] button:text-is("Payments")').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: '.vimad-evidence/ex0307/01-payments-lens.png' });
const lens = await page.locator('section[aria-label="Payment exceptions"]').count();
console.log('lens sections:', lens);
await page.goto(WEB + '/app/exceptions');
await page.waitForTimeout(2500);
const boxes = page.locator('section[aria-label="Needs attention"] tbody input[type="checkbox"]');
await boxes.nth(0).check();
await boxes.nth(1).check();
await page.waitForTimeout(500);
await page.screenshot({ path: '.vimad-evidence/ex0307/02-bulk-bar.png' });
const bulkBar = await page.locator('text=2 selected').count();
console.log(JSON.stringify({ paymentsLens: lens, bulkBar }));
console.log('=== SHIPPED: EX-03 + EX-07 spot-check ===');
await browser.close();
