import { chromium } from 'playwright';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(path.resolve('apps/api/package.json'));
const jwt = require('jsonwebtoken');
const API = 'http://localhost:3001';
const WEB = 'http://localhost:5173';
const login = await fetch(API + '/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ tenantSlug: 'demo-hotel', email: 'admin@demo.com', password: 'admin123' }) }).then((r) => r.json());
const token = login.data?.token ?? login.token;
const res = await fetch(API + '/v1/reservations?limit=100', { headers: { Authorization: `Bearer ${token}` } }).then((r) => r.json());
const list = res?.data?.reservations ?? res?.data ?? res ?? [];
const arr = Array.isArray(list) ? list : [];
const rsv = arr.find((x) => x.status === 'checked_in') ?? arr[0];
const env = fs.readFileSync('apps/api/.env', 'utf8');
const secret = env.match(/^JWT_SECRET=(.+)$/m)[1].trim();
const gtoken = jwt.sign({ scope: 'guest-portal', reservationId: rsv.id, tenantId: 'cmvpvm9cr0000afx46emxw02w' }, secret, { expiresIn: '2h' });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 414, height: 896 } });
await ctx.addInitScript((t) => sessionStorage.setItem('gp_token', t), gtoken);
const page = await ctx.newPage();
await page.goto(WEB + '/guest-portal/billing');
await page.waitForTimeout(4000);
await page.screenshot({ path: '.vimad-evidence/p73-portal/01-guest-folio-receipt.png' });
const ok = await page.evaluate(() => document.body.innerText.includes('Folio') && !document.body.innerText.includes('open the conversation'));
console.log('guest folio receipt rendered:', ok);
console.log('=== SHIPPED: P7.3 portal receipt evidence ===');
await browser.close();
