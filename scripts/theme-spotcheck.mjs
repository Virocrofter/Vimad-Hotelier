import { chromium } from 'playwright';
const WEB = 'http://localhost:5173';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(WEB + '/auth/login');
await page.waitForSelector('#tenantSlug');
await page.waitForTimeout(800);
await page.screenshot({ path: '.vimad-evidence/theme-migration/01-login-dark.png' });
await page.locator('#tenantSlug').fill('demo-hotel');
await page.locator('#email').fill('admin@demo.com');
await page.locator('#password').fill('admin123');
await page.locator('button[type="submit"]').click();
await page.waitForURL('**/app/**', { timeout: 20000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: '.vimad-evidence/theme-migration/02-dashboard-dark.png' });
const bg = await page.evaluate(() => getComputedStyle(document.body).backgroundColor);
console.log('body bg:', bg);
console.log('=== SHIPPED: theme-migration visual spot-check captured ===');
await browser.close();
