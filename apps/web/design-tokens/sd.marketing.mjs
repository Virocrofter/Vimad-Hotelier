#!/usr/bin/env node
/* DS-M1 — Ember & Paper Marketing Edition token pipeline (two-system doctrine).
 * marketing-tokens.json is the ONLY source of truth for marketing surfaces;
 * product tokens (tokens.json) are never touched by this build.
 * Output is scoped to [data-vimad-marketing] so product routes are visually
 * unaffected even though the SPA shares a bundle.
 * Run (from apps/web): npm run tokens:build:marketing */
import StyleDictionary from 'style-dictionary';

const sd = new StyleDictionary({
  source: ['design-tokens/marketing-tokens.json'],
  hooks: {
    formats: {
      'vimad/marketing-css': ({ dictionary }) =>
        '/* GENERATED by design-tokens/sd.marketing.mjs from marketing-tokens.json (DS-M1). */\n' +
        '/* Do not edit — change the JSON source and rebuild. Scoped: [data-vimad-marketing] */\n\n' +
        '[data-vimad-marketing] {\n' +
        dictionary.allTokens
          .map((t) => `  --mk-${t.path.slice(1).join('-')}: ${t.$value ?? t.value};`)
          .join('\n') +
        '\n}\n',
    },
  },
  platforms: {
    web: {
      files: [{ destination: 'src/styles/generated/marketing.css', format: 'vimad/marketing-css' }],
    },
  },
});
await sd.buildAllPlatforms();
console.log('marketing tokens built -> src/styles/generated/marketing.css');
